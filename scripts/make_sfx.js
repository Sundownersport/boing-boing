// Generates src/sounds.h. Run: node scripts/make_sfx.js
//
// Each sound is a list of 60 Hz frames. A frame sets all four FM operators of
// one channel: operator 0 feeds 1, 1 feeds 2, 2 feeds 3, and 3 is heard.
// Pitches are note numbers (C4 = 60) and may be fractional, so sounds glide.
// Levels run 0-1.

const fs = require('fs');
const path = require('path');

const A4_INCREMENT = 4125;
const MAX_NOTE = 96;

function increment(note) {
    return Math.max(1, Math.min(0xFFFF, Math.round(A4_INCREMENT * 2 ** ((Math.min(note, MAX_NOTE) - 69) / 12))));
}

function level(l) {
    l = Math.max(0, Math.min(1, l));
    return Math.round(256 - (256 / Math.PI) * Math.acos(l)) & 255;
}

const ease = t => 1 - (1 - t) ** 2;
const lerp = (a, b, t) => a + (b - a) * t;

// note, carrier level, modulator level and ratio, optional noise (operators 0-1)
function frame({ note, amp, mod = 0, ratio = 1, noise = 0, noiseRatio = 1.41 }) {
    return [
        [noise, note + 12 * Math.log2(noiseRatio * 1.37)],
        [noise, note + 12 * Math.log2(noiseRatio)],
        [mod, note + 12 * Math.log2(ratio)],
        [amp, note],
    ];
}

function sound(frames, fn, feedback = 0) {
    return { feedback, frames: Array.from({ length: frames }, (_, i) => frame(fn(i, i / (frames - 1)))) };
}

function glideNotes(list, each, opts = {}) {
    const { slide = 2, amp = 0.8, decay = 0.6, mod = 0.4, ratio = 2 } = opts;
    const total = list.length * each + (opts.tail || 0);
    return sound(total, i => {
        const k = Math.min(list.length - 1, Math.floor(i / each));
        const local = i - k * each;
        const prev = k ? list[k - 1] : list[0];
        const note = local < slide && k ? lerp(prev, list[k], ease((local + 1) / slide)) : list[k];
        const last = k === list.length - 1;
        const t = last ? (i - k * each) / (total - k * each) : local / each;
        return { note, amp: amp * (1 - decay * t), mod: mod * (1 - t), ratio };
    });
}

const sounds = {
    bounce: sound(16, (i, t) => ({
        note: i < 2 ? lerp(57, 50, i) : lerp(50, 71, ease((i - 1) / 14)),
        amp: 0.95 * (1 - t) ** 1.2 + 0.08,
        mod: 0.7 * (1 - t) ** 1.5,
        ratio: 2,
    })),
    spring: sound(26, (i, t) => ({
        note: i < 2 ? lerp(52, 43, i) : lerp(43, 76, ease((i - 1) / 24)),
        amp: 1 * (1 - t) ** 1.1 + 0.08,
        mod: 0.85 * (1 - t) ** 1.3,
        ratio: 2,
    })),
    lowpad: sound(10, (i, t) => ({ note: lerp(57, 41, ease(t)), amp: 0.9 * (1 - t) + 0.05, mod: 0.6 * (1 - t), ratio: 0.5 })),
    dash: sound(12, (i, t) => ({ note: lerp(55, 86, ease(t)), amp: 0.85 * (1 - t * 0.8), mod: 0.5, ratio: 1, noise: 0.25 * (1 - t) }), 0.2),
    crack: sound(4, (i, t) => ({ note: 38 + (i % 2) * 5, amp: 0.8 * (1 - t), mod: 0.9, ratio: 1.5, noise: 0.9 }), 0.9),
    break: sound(10, (i, t) => ({ note: lerp(45, 33, t) + (i % 2) * 4, amp: 0.95 * (1 - t), mod: 1, ratio: 1.5, noise: 1 }), 1),
    heart: glideNotes([76, 83], 5, { tail: 6, amp: 0.8, mod: 0.45, ratio: 3 }),
    key: glideNotes([84, 88, 91, 96], 3, { tail: 8, amp: 0.75, mod: 0.4, ratio: 3 }),
    unlock: glideNotes([72, 76, 79, 84], 5, { tail: 12, amp: 0.85, mod: 0.4, ratio: 2 }),
    teleport: sound(24, (i, t) => ({ note: 58 + 9 * Math.sin(i * 0.75) + 14 * t, amp: 0.8 * (1 - t * 0.7), mod: 0.5 + 0.4 * Math.sin(i * 0.5), ratio: 1.5 })),
    death: sound(34, (i, t) => ({ note: lerp(76, 38, t) + 1.2 * Math.sin(i * 1.4), amp: 0.95 * (1 - t * 0.85), mod: 0.3 + 0.6 * t, ratio: 1, noise: 0.2 * t }), 0.3),
    clear: glideNotes([72, 76, 79, 84], 8, { tail: 18, amp: 0.85, mod: 0.4, ratio: 2, decay: 0.4 }),
    win: glideNotes([72, 76, 79, 84, 79, 84, 88], 8, { tail: 36, amp: 0.85, mod: 0.4, ratio: 2, decay: 0.3 }),
};

const lines = [
    '// Generated by scripts/make_sfx.js. Edit that file, not this one.',
    '',
];
const names = Object.keys(sounds);
names.forEach((name, i) => lines.push(`#define SND_${name} ${i}`));
lines.push('', '#pragma rodata-name (push, "PROG0")');
let total = 0;
for (const name of names) {
    const { feedback, frames } = sounds[name];
    if (frames.length > 255) throw new Error(`${name}: ${frames.length} frames, max 255`);
    const bytes = [frames.length, level(feedback)];
    for (const ops of frames) {
        bytes.push(...ops.map(([l]) => level(l)));
        bytes.push(...ops.map(([, n]) => increment(n) >> 8));
        bytes.push(...ops.map(([, n]) => increment(n) & 255));
    }
    total += bytes.length;
    lines.push(`static const unsigned char snd_${name}[] = { ${bytes.join(', ')} };`);
    console.log(`${name.padEnd(9)} ${frames.length} frames, ${bytes.length} bytes`);
}
lines.push(`static const unsigned char* const sound_table[] = { ${names.map(n => `snd_${n}`).join(', ')} };`);
lines.push('#pragma rodata-name (pop)', '');
fs.writeFileSync(path.join(__dirname, '..', 'src', 'sounds.h'), lines.join('\n'));
console.log(`total ${total} bytes`);
